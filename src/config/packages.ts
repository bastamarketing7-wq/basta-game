/**
 * باقات بسطة — ملف إعداد منفصل وقابل للتعديل.
 *
 * مهم: لم تُرفق قائمة الباقات المعتمدة (الاسم، السعر، المدة، المحتوى) ضمن ملفات المشروع.
 * لذلك القائمة فارغة عمدًا. لا يجوز تأليف اسم باقة أو سعر أو مدة أو ضمان.
 *
 * عند اعتماد الباقات رسميًا: أضفها داخل PACKAGES بنفس البنية أدناه، وسيقوم
 * محرك الترشيح بربطها بالمشكلات ذات الأولوية تلقائيًا.
 */

export interface BastaPackage {
  /** معرّف داخلي ثابت */
  id: string
  /** اسم الباقة كما هو معتمد رسميًا */
  name: string
  /** السعر كما هو معتمد. اتركه فارغًا إن لم يكن معتمدًا. */
  price?: string
  /** مدة الباقة كما هي معتمدة */
  duration?: string
  /** بنود الباقة كما وردت في الملف المعتمد */
  includes: string[]
  /**
   * المشكلات التي تعالجها هذه الباقة.
   * تُستخدم لربط الباقة بالمشكلات ذات الأولوية عند الترشيح.
   */
  solves: string[]
  /** ملاحظة تفرقة ميزانية الإعلانات عن أتعاب الإدارة إن وُجدت في الملف المعتمد */
  adBudgetNote?: string
}

/**
 * القائمة الرسمية للباقات.
 * فارغة حتى تُرفق قائمة الباقات المعتمدة.
 */
export const PACKAGES: BastaPackage[] = []

/** الرسالة الإلزامية عند عدم توفر قائمة باقات معتمدة. */
export const PACKAGES_UNAVAILABLE_MESSAGE =
  'لا يمكن اختيار الباقة لعدم توفر قائمة الباقات المعتمدة.'

export const hasApprovedPackages = (): boolean => PACKAGES.length > 0
